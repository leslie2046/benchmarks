import argparse
import os
import random
import statistics
import threading
import time
from concurrent.futures import ThreadPoolExecutor, as_completed

import requests

from env_loader import load_local_env


load_local_env()


TEXTS = [
    "Artificial intelligence is transforming healthcare by enabling more accurate diagnosis, personalized treatment, and efficient medical research.",
    "Large language models have demonstrated remarkable capabilities in text understanding, summarization, reasoning, and code generation tasks.",
    "Cloud computing provides scalable infrastructure that allows developers to deploy applications efficiently across multiple geographic regions.",
    "Modern recommendation systems leverage embeddings to represent users and items in a shared semantic vector space.",
    "Vector databases are designed for efficient similarity search using high-dimensional embedding vectors generated by neural networks.",
    "Deep learning models require significant computational resources but often achieve state-of-the-art performance on benchmark datasets.",
    "Autonomous driving systems integrate computer vision, sensor fusion, and reinforcement learning to navigate complex environments safely.",
    "Natural language processing techniques continue to improve multilingual understanding and cross-lingual information retrieval.",
    "High-performance GPUs accelerate transformer inference through optimized matrix multiplication and memory management.",
    "Distributed systems improve availability and scalability by replicating data and balancing workloads across multiple servers.",
]

_thread_local = threading.local()


def parse_args():
    parser = argparse.ArgumentParser(description="OpenAI-compatible embedding benchmark")
    parser.add_argument(
        "--base-url",
        default=os.getenv("EMBEDDING_BASE_URL", "https://api.siliconflow.cn/v1/embeddings"),
        help="Endpoint URL (default: EMBEDDING_BASE_URL or SiliconFlow)",
    )
    parser.add_argument(
        "--model",
        default=os.getenv("EMBEDDING_MODEL", "BAAI/bge-m3"),
        help="Model name (default: EMBEDDING_MODEL or BAAI/bge-m3)",
    )
    parser.add_argument("-c", "--concurrency", type=int, default=5)
    parser.add_argument("-n", "--requests", type=int, default=100)
    parser.add_argument("--timeout", type=float, default=60)
    return parser.parse_args()


def get_session():
    if not hasattr(_thread_local, "session"):
        _thread_local.session = requests.Session()
    return _thread_local.session


def percentile(values, percent):
    ordered = sorted(values)
    index = min(int(len(ordered) * percent / 100), len(ordered) - 1)
    return ordered[index]


def validate_args(args):
    if args.concurrency < 1 or args.requests < 1:
        raise SystemExit("--concurrency and --requests must be greater than 0")
    if args.timeout <= 0:
        raise SystemExit("--timeout must be greater than 0")


def benchmark(args):
    api_key = os.getenv("EMBEDDING_API_KEY") or os.getenv("XINFERENCE_API_KEY")
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"

    def worker():
        start = time.perf_counter()
        try:
            response = get_session().post(
                args.base_url,
                headers=headers,
                json={"model": args.model, "input": random.choice(TEXTS)},
                timeout=args.timeout,
            )
            latency = (time.perf_counter() - start) * 1000
            if 200 <= response.status_code < 300:
                return True, latency
            print(f"HTTP {response.status_code}: {response.text[:500]}")
            return False, latency
        except requests.RequestException as exc:
            latency = (time.perf_counter() - start) * 1000
            print(f"Request failed: {exc}")
            return False, latency

    print(f"Model: {args.model} | Concurrency: {args.concurrency} | Requests: {args.requests}")
    started = time.perf_counter()
    with ThreadPoolExecutor(max_workers=args.concurrency) as executor:
        results = list(as_completed(executor.submit(worker) for _ in range(args.requests)))
        samples = [future.result() for future in results]
    elapsed = time.perf_counter() - started

    latencies = [latency for _, latency in samples]
    successes = sum(ok for ok, _ in samples)
    print("\n===== Result =====")
    print(f"Elapsed Time : {elapsed:.2f}s")
    print(f"Success      : {successes}/{args.requests}")
    print(f"Success Rate : {successes / args.requests * 100:.2f}%")
    print(f"QPS          : {args.requests / elapsed:.2f}")
    print(f"Average      : {statistics.mean(latencies):.2f} ms")
    for percent in (50, 95, 99):
        print(f"P{percent:<2}          : {percentile(latencies, percent):.2f} ms")
    print(f"Max          : {max(latencies):.2f} ms")
    print(f"Min          : {min(latencies):.2f} ms")


if __name__ == "__main__":
    cli_args = parse_args()
    validate_args(cli_args)
    benchmark(cli_args)
